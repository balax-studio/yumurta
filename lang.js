window.changeLanguage = function (langStr, playSnd = false) {
    if (playSnd && !window.isMusicMuted) {
        let snd = new Audio('audio/pop-buy.wav');
        snd.volume = 0.8;
        snd.play().catch(e => { });
    }

    if (I18N[langStr]) {
        currentLang = langStr;
        window.currentLang = currentLang;
        localStorage.setItem('chickenIdleLang', currentLang);
        window.P2P_FONT = ['ja', 'zh-cn'].includes(currentLang) ? 'DotGothic16' : (['ko', 'vi'].includes(currentLang) ? 'sans-serif' : 'Press Start 2P');
        window.P2P_SCALE = (window.P2P_FONT === 'Press Start 2P') ? 1.0 : 1.35;

        let targetFont = `"${window.P2P_FONT}", monospace, sans-serif`;
        document.body.style.fontFamily = targetFont;

        // Multiplicador visual: Press Start 2P es muy voluminosa.
        let scaleFactor = window.P2P_SCALE;

        // Aplicar a todos los elementos excepto a las zonas restringidas y cuadrícula de idiomas
        let elems = document.querySelectorAll('button:not(.lang-btn), h1, h2, h3, p, span, input, select, div, a');
        elems.forEach(e => {
            // Ignoramos todo lo que pertenezca a cajas que nunca deben ser traducidas o escaladas
            if (e.closest('#ranking-list') || e.closest('#ranking-status') || e.closest('#topbar')) return;
            // bubble-inner: el tamaño lo gestiona _fitBubble, no debe ser sobreescrito
            if (e.closest('.bubble-inner')) return;
            // pills de boost activo: tamaño fijo en CSS, no escalar
            if (e.closest('#eb-active') || e.closest('#eb-offer')) return;
            // Elementos de números puros: siempre con la fuente original
            if (e.classList.contains('lv-corner') || e.classList.contains('btn-price') || e.classList.contains('upg-info')) return;

            if (e.style) {
                e.style.fontFamily = targetFont;

                // Leer el CSS real aplicado por style.css o inline
                if (!e.dataset.origFontSize) {
                    let comp = window.getComputedStyle(e).fontSize;
                    if (comp && comp.includes('px')) {
                        e.dataset.origFontSize = parseFloat(comp);
                    }
                }

                // Aplicamos el factor
                if (e.dataset.origFontSize) {
                    e.style.fontSize = (parseFloat(e.dataset.origFontSize) * scaleFactor) + 'px';
                }
            }
        });

        // Proteger el branding forzándolo inline preventivamente contra el body proxy
        let topBarH1 = document.querySelector('#topbar h1');
        if (topBarH1) topBarH1.style.fontFamily = `\'Press Start 2P\', monospace`;

        let speedTimer = document.querySelector('#speedrun-timer');
        if (speedTimer) speedTimer.style.fontFamily = `\'Press Start 2P\', monospace`;

        let rankStatus = document.querySelector('#ranking-status');
        if (rankStatus) rankStatus.style.fontFamily = `\'Press Start 2P\', monospace`;

        let rankList = document.querySelector('#ranking-list');
        if (rankList) rankList.style.fontFamily = `\'Press Start 2P\', monospace`;

        document.querySelectorAll('.lang-btn').forEach(b => b.style.fontFamily = `\'Press Start 2P\', monospace`);

        document.querySelectorAll('.lv-corner, .btn-price, .upg-info').forEach(el => {
            el.style.fontFamily = `\'Press Start 2P\', monospace`;
            el.style.fontSize = '';
        });
        // #chickens y #money: solo fontFamily — fontSize lo gestiona _adjustHUDTextSizes y no debe borrarse
        document.querySelectorAll('#chickens, #money').forEach(el => {
            el.style.fontFamily = `\'Press Start 2P\', monospace`;
        });

        let transAuthor = document.getElementById('trans-author');
        if (transAuthor) {
            if (currentLang === 'tr') {
                transAuthor.setAttribute('data-i18n', 'transByEge');
            } else if (currentLang === 'sv') {
                transAuthor.setAttribute('data-i18n', 'transByHermine');
            } else if (currentLang === 'id') {
                transAuthor.setAttribute('data-i18n', 'transByYoga');
            } else {
                transAuthor.setAttribute('data-i18n', (currentLang === 'en' || currentLang === 'es') ? 'transByJc' : 'transByAI');
            }
        }

        // Resaltar visualmente el botón del idioma activo
        document.querySelectorAll('.lang-btn').forEach(btn => {
            if (btn.id === 'lang-' + currentLang) {
                btn.style.transform = 'scale(1.15)';
                btn.style.border = '2px solid white';
                btn.style.zIndex = '10';
                btn.style.boxShadow = '0px 0px 10px rgba(255,255,255,0.5)';
            } else {
                btn.style.transform = 'scale(1)';
                btn.style.border = 'none';
                btn.style.zIndex = '1';
                btn.style.boxShadow = 'none';
            }
        });

        if (window.applyTranslations) window.applyTranslations();
        if (window._refreshPauseTitle) window._refreshPauseTitle();
        if (window.updateUI) window.updateUI();
    }
}

