window.applyTranslations = function () {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerHTML = window.t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const translated = window.t(key);
        el.setAttribute('data-title', translated);
        const descDiv = el.querySelector('.shop-desc-text');
        if (descDiv) descDiv.innerHTML = translated;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', window.t(key));
    });
    // Prado mode names: strip "N. " number prefix from chal title keys
    document.querySelectorAll('[data-prado-name]').forEach(el => {
        const key = el.getAttribute('data-prado-name');
        el.textContent = window.t(key).replace(/^\d+\.\s*/, '');
    });
}

